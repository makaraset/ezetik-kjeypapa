-- CamDigi identity verification attempts (2026-10-27).
--
-- RUN AS:  psql -v ON_ERROR_STOP=1 --single-transaction -f 008_pdl_identity_verification.sql
-- Idempotent: IF NOT EXISTS throughout.
--
-- SBF asked for NID image + liveness verification through CamDigi
-- (POST /verified-info-idimage-liveness). It runs after the customer has
-- submitted their account request and verified their phone, against the
-- identity they submitted; see PdlIdentityVerificationService. One row per
-- attempt, so the LPO sees every try, and the per-request attempt cap can be
-- a rolling window rather than a lifetime limit.
--
-- APPLY BEFORE DEPLOYING. SBF UAT runs with ddl-auto off, so without this the
-- table does not exist and every verification fails. On a dev database with
-- ddl-auto=update, Hibernate would create the table but not the composite
-- index the attempt cap reads; apply this first there too. The entity maps
-- status through a converter, so neither path adds a CHECK on it.
--
-- Deliberately absent:
--   * a CHECK on status — the outcomes will grow once SBF documents their
--     error codes (an info mismatch is not a face mismatch);
--   * any column for the capture or the ID image — the capture is biometric
--     data and is passed through, never stored, until SBF says otherwise.

CREATE TABLE IF NOT EXISTS public.pdl_identity_verification (
    id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at           timestamp(6) with time zone NOT NULL,
    updated_at           timestamp(6) with time zone,
    account_request_id   integer NOT NULL REFERENCES public.pdl_account_request(id),
    -- CHALLENGED | IN_FLIGHT | PASSED | FAILED | ERROR
    status               character varying(20) NOT NULL,
    -- sha256 of the challenge id; the id itself is only ever held by the app.
    challenge_hash       character varying(64) NOT NULL,
    actions              character varying(255) NOT NULL DEFAULT '',
    challenge_expires_at timestamp(6) with time zone NOT NULL,
    submitted_at         timestamp(6) with time zone,
    completed_at         timestamp(6) with time zone,
    http_status          integer,
    -- CamDigi's own envelope: {data, error, message}.
    sbf_error            integer,
    sbf_message          character varying(500),
    -- Why there was no usable reply: UNREACHABLE | NO_REPLY | SERVER_ERROR | REJECTED | BAD_REPLY.
    error_kind           character varying(30),
    -- CamDigi's reply with every long string elided (it may echo images back).
    response_excerpt     text,
    latency_ms           integer,
    liveness_bytes       integer,
    client_ip            character varying(64),
    mock                 boolean NOT NULL DEFAULT false
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_pdl_idv_challenge
    ON public.pdl_identity_verification (challenge_hash);

CREATE INDEX IF NOT EXISTS ix_pdl_idv_request
    ON public.pdl_identity_verification (account_request_id, submitted_at);
