-- The twelve tables our application adds. NOTHING here touches SBF's existing
-- TFF tables — that is the point of the file, and it was produced in a way that
-- proves it rather than asserting it:
--
--   1. pg_dump of SBF UAT (10.32.2.33), schema only  -> their 16 tables
--   2. loaded into a throwaway postgres:18 container -> an exact copy, no data
--   3. our image run against the copy with ddl-auto=update
--   4. pg_dump of the copy, restricted to pdl_*      -> this file
--
-- Step 4's counterpart — dumping the copy EXCLUDING pdl_* and diffing against
-- step 1 — is what found the two drifts documented in the deployment runbook.
-- Re-run that diff if the entities change; it is the only honest way to know
-- what a deploy would do to a database you do not own.
--
